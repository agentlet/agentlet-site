#!/usr/bin/env node
/**
 * Builds the `agentlet-demos` npm package contents into
 * packages/agentlet-demos/dist/, from src/agentlets/known-sites/manifest.ts,
 * the single source of truth for the agentlets that run on well-known
 * third-party sites.
 *
 * Output:
 *   loader.js            esbuild IIFE of src/scripts/known-sites-loader.ts,
 *                          with the exact version of this package and of
 *                          agentlet-core baked in
 *   registry.js          generated registry, agentlet-core's script-injection
 *                          format, plus a `pattern` per demo (ignored by the
 *                          core, read by the loader and the launcher)
 *   agentlets/<id>.js    one esbuild IIFE bundle per manifest entry, plus the
 *                          launcher
 *
 * agentlet-core itself is NOT copied here. The loader loads it from
 * jsDelivr at the exact version found in node_modules/agentlet-core (see
 * known-sites-loader.ts), or from the site's own /cdn/v1/ when served from
 * the local dev server.
 *
 * dist/ is gitignored and rebuilt from scratch on every run. CI builds it
 * (.github/workflows/build.yml) and the publish workflow builds it again
 * before `npm publish` (.github/workflows/publish-demos.yml).
 *
 * Usage: node scripts/build-known-sites.mjs
 */

import { build } from 'esbuild';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadTsModule } from './lib/load-ts-module.mjs';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const SRC = join(ROOT, 'src/agentlets/known-sites');
const PACKAGE_DIR = join(ROOT, 'packages/agentlet-demos');
const OUT = join(PACKAGE_DIR, 'dist');

function readVersion(packageJsonPath) {
	const { version } = JSON.parse(readFileSync(packageJsonPath, 'utf8'));
	if (!/^\d+\.\d+\.\d+$/.test(version)) {
		throw new Error(`Expected an exact x.y.z version in ${packageJsonPath}, found "${version}".`);
	}
	return version;
}

const DEMOS_VERSION = readVersion(join(PACKAGE_DIR, 'package.json'));
const CORE_VERSION = readVersion(join(ROOT, 'node_modules/agentlet-core/package.json'));

async function buildBundle(entryPoint, outfile, extra = {}) {
	await build({
		entryPoints: [entryPoint],
		bundle: true,
		minify: true,
		format: 'iife',
		platform: 'browser',
		target: 'es2020',
		outfile,
		logLevel: 'warning',
		...extra,
	});
}

/**
 * agentlet-core's registry contract (see /docs/guides/script-injection/): a
 * script that builds a registry object and dispatches it as
 * `agentletRegistryLoaded`, synchronously, so it loads through `<script src>`
 * on a page with a strict CSP and across origins.
 *
 * Entry URLs are resolved at run time from the registry script's own
 * address (`document.currentScript.src`), so the same file works from
 * jsDelivr at an exact version and from the local dev server, with no URL
 * written into the build. The fallback used when `currentScript` is not
 * available is the exact jsDelivr path of this version.
 *
 * Demos are `lazy: true`: the core does not load their bundles at start-up.
 * The launcher, or the loader for a page with a single demo, loads one on
 * demand. Only the launcher is eager.
 */
function buildRegistry({ launcher, agentlets }) {
	const entries = [
		{
			name: launcher.id,
			file: `agentlets/${launcher.id}.js`,
			module: launcher.className,
			description: launcher.description,
		},
		...agentlets.map((entry) => ({
			name: entry.id,
			file: `agentlets/${entry.id}.js`,
			module: entry.className,
			description: entry.description,
			site: entry.site,
			pattern: entry.pattern,
			lazy: true,
		})),
	];

	const contents = `// Generated by scripts/build-known-sites.mjs from
// src/agentlets/known-sites/manifest.ts. Do not edit by hand.
//
// Format: agentlet-core's registry script contract. Each entry's "file" is
// resolved against this script's own address, below. "pattern" is not read by
// the core; the loader and the launcher read it.
(function () {
	'use strict';
	var fallback = 'https://cdn.jsdelivr.net/npm/agentlet-demos@${DEMOS_VERSION}/dist/';
	var script = document.currentScript;
	var own = script && script.src ? script.src.replace(/[?#].*$/, '') : '';
	var base = own ? own.replace(/[^/]*$/, '') : fallback;
	var registry = ${JSON.stringify({ version: DEMOS_VERSION, agentlets: entries }, null, 2).replace(/\n/g, '\n\t')};
	registry.agentlets.forEach(function (entry) {
		entry.url = base + entry.file;
		delete entry.file;
	});
	window.dispatchEvent(new CustomEvent('agentletRegistryLoaded', { detail: registry }));
})();
`;
	writeFileSync(join(OUT, 'registry.js'), contents, 'utf8');
}

async function main() {
	rmSync(OUT, { recursive: true, force: true });
	mkdirSync(join(OUT, 'agentlets'), { recursive: true });

	const manifest = await loadTsModule(join(SRC, 'manifest.ts'), '.known-sites-manifest.generated.mjs');
	const launcher = manifest.KNOWN_SITES_LAUNCHER;
	const agentlets = manifest.KNOWN_SITE_AGENTLETS;

	for (const entry of [launcher, ...agentlets]) {
		await buildBundle(join(SRC, `${entry.file}.ts`), join(OUT, 'agentlets', `${entry.id}.js`));
	}

	buildRegistry({ launcher, agentlets });

	await buildBundle(join(ROOT, 'src/scripts/known-sites-loader.ts'), join(OUT, 'loader.js'), {
		define: {
			__DEMOS_VERSION__: JSON.stringify(DEMOS_VERSION),
			__CORE_VERSION__: JSON.stringify(CORE_VERSION),
		},
	});

	console.log(
		`Built packages/agentlet-demos/dist/ (agentlet-demos@${DEMOS_VERSION}, agentlet-core@${CORE_VERSION}: loader, registry, ${agentlets.length} demo bundle(s): ${agentlets.map((e) => e.id).join(', ')}, plus the launcher)`,
	);
}

main().catch((error) => {
	console.error(error);
	process.exit(1);
});
