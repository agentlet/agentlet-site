/**
 * "Receipt to expense report": reads the site's own sample receipt, shows
 * what an AI would receive from the sandbox form (src/components/landing/
 * TrySandbox.astro), fills that form with a recorded response, and
 * highlights what changed. Never submits the form.
 *
 * Home page only: the sandbox this agentlet operates on only exists on
 * `/`. checkPattern() only gates automatic URL-based activation (see
 * agentlet-core's ModuleRegistry.findMatchingModule()), not a manual "Try
 * it" click from the launcher (src/agentlets/launcher.ts), which activates
 * a module directly. _render() below defends against that gap by checking
 * for the sandbox form itself and showing a clear message instead of
 * failing silently if it is missing (e.g. this agentlet launched from a
 * docs page).
 */
const HOME_PAGE_PATTERN = '^https?:\\/\\/[^/]+\\/?(?:[?#].*)?$';

const FILE = 'expense-receipt';
const RECEIPT_PDF_URL = '/demo/receipt.pdf';
const FORM_SELECTOR = '#expense-form';
const DEMO_SECTION_URL = '/#demo';

/**
 * Must match src/scripts/demo-loader.ts's own `PDF_WORKER_URL` (not
 * exported from there, so duplicated here; see the comment on
 * `_ensurePdfWorker()` below for why this module also needs it directly).
 */
const PDF_WORKER_URL = '/cdn/v1/pdf.worker.min.mjs';

/**
 * Recorded response for the one receipt this agentlet supports (public/demo/
 * receipt.pdf, generated by scripts/generate-demo-receipt.mjs). Keep these
 * values in sync with that script by hand: there is no shared runtime
 * import between a Node build script and this browser bundle. Vendor
 * Riverside Bistro, dated 14 Mar 2026, subtotal 66.00, VAT (20%) 13.20,
 * total 79.20 GBP, category "Meals and entertainment".
 *
 * Keys match the sandbox form fields' `name` attributes: FormFiller.
 * fillFromAIData() (agentlet-core's src/utils/data-processing/FormFiller.ts)
 * looks up each exported element by `userValues[element.name] ||
 * userValues[element.id]`, and every sandbox field is named after its
 * purpose (see TrySandbox.astro).
 */
const RECORDED_AI_RESPONSE: Record<string, FormFillValue> = {
	vendor: 'Riverside Bistro',
	date: '2026-03-14',
	amount: '79.20',
	vatAmount: '13.20',
	currency: 'GBP',
	category: 'meals',
};

